#!/usr/bin/env node
// Writes lib/agent-bridge-routes.generated.ts: every admin page API the T4A agent may
// call through the bridge (POST /api/agent/admin, lib/agent-bridge.ts), with the
// route module, its HTTP methods and the doc comment above each handler (the agent
// reads those to know what a route does and what body it takes).
//
//   node scripts/gen-agent-bridge.mjs          # rewrite the file
//   node scripts/gen-agent-bridge.mjs --check  # exit 1 if it is out of date (tests run this)
//
// Run it after adding, removing or documenting an admin API route.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(import.meta.url), "..", "..");
const OUT = join(root, "lib", "agent-bridge-routes.generated.ts");

// Route trees the bridge serves (the admin pages' own APIs).
const PREFIXES = ["/api/admin/", "/api/automation/", "/api/builder/", "/api/partners/", "/api/warranty/"];
// Never through the bridge, with the reason (shown in the generated file).
export const EXCLUDED = {
  "/api/admin/me": "the signed-in browser user, meaningless for the agent",
  "/api/admin/documents/me": "the signed-in browser user's own documents",
  "/api/admin/portal/impersonate": "sets a browser cookie (view as someone)",
  "/api/admin/preorder/campaigns/[id]/invite": "returns the campaign's secret magic-link token",
  "/api/admin/preorder/products/image": "file upload (multipart)",
  "/api/admin/preorder/products/import": "file upload (multipart)",
  "/api/admin/preorder/vat/import": "file upload (multipart)",
};
const METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE"];

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (name === "route.ts") out.push(p);
  }
  return out;
}

/** The `//` comment block right above line `i` (blank comment lines kept, stops at code). */
function commentAbove(lines, i) {
  const block = [];
  for (let j = i - 1; j >= 0; j--) {
    const t = lines[j].trim();
    if (t.startsWith("//")) block.unshift(t.replace(/^\/\/\s?/, ""));
    else if (t === "" && block.length === 0) continue;
    else break;
  }
  return block.join("\n").trim();
}

const routes = [];
for (const file of walk(join(root, "app", "api")).sort()) {
  const rel = relative(join(root, "app"), file).split(sep).join("/");
  const pattern = "/" + rel.replace(/\/route\.ts$/, "");
  if (!PREFIXES.some((p) => pattern.startsWith(p))) continue;
  if (pattern in EXCLUDED) continue;
  const src = readFileSync(file, "utf8");
  const lines = src.split("\n");
  const methods = {};
  lines.forEach((line, i) => {
    const m = /^export\s+(?:async\s+function|const)\s+(GET|POST|PUT|PATCH|DELETE)\b/.exec(line);
    if (m && METHODS.includes(m[1])) methods[m[1]] = commentAbove(lines, i);
  });
  if (Object.keys(methods).length === 0) continue;
  // The file's leading comment (before the first import) often explains the whole route.
  const firstCode = lines.findIndex((l) => l.trim() && !l.trim().startsWith("//"));
  const header = firstCode > 0 ? commentAbove(lines, firstCode) : "";
  routes.push({ pattern, importPath: "@/app/" + rel.replace(/\.ts$/, ""), methods, header });
}

const q = (s) => JSON.stringify(s);
const body = [
  "// GENERATED by scripts/gen-agent-bridge.mjs — do not edit by hand; run `node scripts/gen-agent-bridge.mjs`.",
  "// The admin page APIs the T4A agent may call through POST /api/agent/admin (lib/agent-bridge.ts).",
  "// Left out on purpose:",
  ...Object.entries(EXCLUDED).map(([p, why]) => `//   ${p}: ${why}`),
  'import type { BridgeRoute } from "@/lib/agent-bridge-types";',
  ...routes.map((r, i) => `import * as r${i} from ${q(r.importPath)};`),
  "",
  "export const BRIDGE_ROUTES: BridgeRoute[] = [",
  ...routes.map(
    (r, i) =>
      `  { pattern: ${q(r.pattern)}, mod: r${i} as unknown as BridgeRoute["mod"], header: ${q(r.header)}, methods: {\n` +
      Object.entries(r.methods).map(([m, doc]) => `    ${m}: ${q(doc)},`).join("\n") +
      "\n  } },",
  ),
  "];",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing */ }
  if (current !== body) {
    console.error("lib/agent-bridge-routes.generated.ts is out of date: run `node scripts/gen-agent-bridge.mjs`.");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${relative(root, OUT)}: ${routes.length} routes`);
}
